import { describe, it, expect } from 'vitest';
import { readFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
import { generateSpec } from '../lib/to-spec.js';
import { planSteps, routePattern } from '../lib/plan.js';

const here = dirname(fileURLToPath(import.meta.url));
const fixture = (name) => JSON.parse(readFileSync(join(here, 'fixtures', name), 'utf8'));
const BIN = join(here, '..', 'bin', 'to-spec.js');

describe('generateSpec snapshots', () => {
  it('B1 hero replay (expectation visible)', () => {
    expect(generateSpec(fixture('b1-settle.replay.json'), { iid: 12 })).toMatchSnapshot();
  });
  it('B2 replay (expectation null, masked input, goto, toggle, explicit submit)', () => {
    expect(generateSpec(fixture('b2-blank-name.replay.json'), { iid: 13 })).toMatchSnapshot();
  });
  it('flow file with text expectation and custom base-url env', () => {
    expect(generateSpec(fixture('change-currency.flow.json'), { iid: 14, baseUrlEnv: 'HEAD_URL' })).toMatchSnapshot();
  });
});

describe('generateSpec contract', () => {
  const code = generateSpec(fixture('b1-settle.replay.json'), { iid: 12 });
  it('has the required header, title, baseURL and reset', () => {
    expect(code.split('\n')[0]).toBe('// Generated by ShakeFix from report r_20261011_8f3a2b — must FAIL before the fix and PASS after.');
    expect(code).toContain(`test("issue #12: settle button does nothing", async ({ page, request }) => {`);
    expect(code).toContain(`test.use({ baseURL: process.env.BASE_URL || "http://localhost:8080" });`);
    expect(code).toContain(`await request.post('/api/__test/reset').catch(() => undefined);`);
    expect(code).toContain(`await page.goto("/");`);
  });
  it('maps actions to Playwright calls by testid', () => {
    expect(code).toContain(`await page.getByTestId("total-input").fill("1000");`);
    expect(code).toContain(`await page.getByTestId("tip-select").selectOption("10");`);
    expect(code).toContain(`await page.getByTestId("confirm-settle-btn").click();`);
    expect(code).toMatch(/await page\.waitForURL\(\/.*bill\\\/\[\^\/\?#\]\+\\\/settle/);
    expect(code).toContain(`await expect(page.getByTestId("settled-banner")).toBeVisible();`);
  });
  it('null expectation asserts no console errors and no error banner', () => {
    const c = generateSpec(fixture('b2-blank-name.replay.json'), { iid: 13 });
    expect(c).toContain(`await expect(page.getByTestId('error-banner')).toBeHidden();`);
    expect(c).toContain('expect(errors).toEqual([]);');
    expect(c).toContain('// Reporter note: app went blank * / after I saved with an empty name'); // comment-breaking text neutralised
  });
  it('hidden + text states', () => {
    const r = fixture('b1-settle.replay.json');
    expect(generateSpec({ ...r, expectation: { testid: 'error-banner', state: 'hidden' } }, { iid: 1 })).toContain(`await expect(page.getByTestId("error-banner")).toBeHidden();`);
    expect(generateSpec({ ...r, expectation: { testid: 'bill-total', state: 'text', text: '₹1,000.00' } }, { iid: 1 })).toContain(`await expect(page.getByTestId("bill-total")).toHaveText("₹1,000.00");`);
  });
  it('requires iid', () => {
    expect(() => generateSpec(fixture('b1-settle.replay.json'), {})).toThrow(/iid/);
  });
});

describe('planSteps / routePattern', () => {
  it('wildcards id-like segments only', () => {
    const re = new RegExp(routePattern('/bill/7/settle'));
    expect(re.test('http://localhost:8080/bill/42/settle')).toBe(true);
    expect(re.test('http://localhost:8080/bill/42/settle?x=1')).toBe(true);
    expect(re.test('http://localhost:8080/bill/42')).toBe(false);
    const nw = new RegExp(routePattern('/bill/new'));
    expect(nw.test('https://a.run.app/bill/new')).toBe(true);
    expect(nw.test('https://a.run.app/bill/7')).toBe(false);
    expect(new RegExp(routePattern('/')).test('http://localhost:8080/')).toBe(true);
    expect(new RegExp(routePattern('/bill/k3x9a2')).test('http://h/bill/zz9q8w')).toBe(true);
  });
  it('skips the submit that a click caused; waits for app navigations; gotos the rest', () => {
    const ops = planSteps(fixture('b1-settle.replay.json').actions).map((s) => s.op);
    expect(ops).toEqual(['click', 'waitForURL', 'fill', 'fill', 'fill', 'click', 'fill', 'click', 'fill', 'click', 'skip', 'waitForURL', 'select', 'click', 'waitForURL', 'click']);
    const ops2 = planSteps(fixture('b2-blank-name.replay.json').actions).map((s) => s.op);
    expect(ops2).toEqual(['goto', 'click', 'waitForURL', 'fill', 'fill', 'fill', 'fill', 'check', 'submit', 'waitForURL']);
  });
});

describe('bin/to-spec.js CLI', () => {
  it('writes the spec (creating folders) and matches generateSpec', () => {
    const dir = mkdtempSync(join(tmpdir(), 'shakefix-'));
    try {
      const out = join(dir, 'tests', 'regressions', 'issue-12.spec.ts');
      const stdout = execFileSync(process.execPath, [BIN, join(here, 'fixtures', 'b1-settle.replay.json'), out, '--iid', '12'], { encoding: 'utf8' });
      expect(stdout).toContain('wrote');
      expect(readFileSync(out, 'utf8')).toBe(generateSpec(fixture('b1-settle.replay.json'), { iid: 12 }));
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
  it('exits 1 with usage when --iid is missing', () => {
    let status = 0;
    let stderr = '';
    try {
      execFileSync(process.execPath, [BIN, 'a.json', 'b.spec.ts'], { encoding: 'utf8', stdio: 'pipe' });
    } catch (e) {
      status = e.status;
      stderr = String(e.stderr);
    }
    expect(status).toBe(1);
    expect(stderr).toContain('Usage:');
  });
});

describe('navigate with value (a page load the user did)', () => {
  it('is driven with goto even right after a change, not waited for', () => {
    const steps = planSteps([
      { t: 0, type: 'change', testid: 'default-currency-select', selector: '[data-testid="default-currency-select"]', value: 'USD', route: '/settings' },
      { t: 900, type: 'navigate', selector: 'window', route: '/bill/new', value: '/bill/new' },
    ]);
    expect(steps[1]).toMatchObject({ op: 'goto', route: '/bill/new' });
  });
});
