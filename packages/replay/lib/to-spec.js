// replay.json → Playwright regression spec (string). Zero runtime dependencies.
import { normalizeFlow, planSteps } from './plan.js';

const q = (s) => JSON.stringify(String(s));
const comment = (s) => String(s).replace(/\*\//g, '* /').replace(/[\r\n]+/g, ' ').trim();

function locator(target) {
  return target.testid ? `page.getByTestId(${q(target.testid)})` : `page.locator(${q(target.selector)})`;
}

function stepCode(step) {
  const a = step.action;
  const desc = `${step.index + 1}. ${a.type}${a.testid ? ' ' + a.testid : a.selector && a.selector !== 'window' ? ' ' + a.selector : ''}${a.type === 'navigate' ? ' → ' + a.route : ''}`;
  const label = `// ${comment(desc)}`;
  switch (step.op) {
    case 'click':
      return [label, `await ${locator(step.target)}.click();`];
    case 'fill':
      return [label + (step.masked ? ' (value masked by the SDK — placeholder used)' : ''), `await ${locator(step.target)}.fill(${q(step.value)});`];
    case 'select':
      return [label, `await ${locator(step.target)}.selectOption(${q(step.value)});`];
    case 'check':
      return [label, `await ${locator(step.target)}.setChecked(${step.value});`];
    case 'submit':
      return [label, `await ${locator(step.target)}.evaluate((form) => (form as HTMLFormElement).requestSubmit());`];
    case 'waitForURL':
      return [label, `await page.waitForURL(/${step.pattern}/);`];
    case 'goto':
      return [label, `await page.goto(${q(step.route)});`];
    default:
      return [`${label} — skipped: ${comment(step.reason || '')}`];
  }
}

function expectationCode(exp) {
  const loc = `page.getByTestId(${q(exp.testid)})`;
  if (exp.state === 'hidden') return [`await expect(${loc}).toBeHidden();`];
  if (exp.state === 'text') return [`await expect(${loc}).toHaveText(${q(exp.text ?? '')});`];
  return [`await expect(${loc}).toBeVisible();`];
}

export function specTitle(flow, iid) {
  const note = String(flow.note).replace(/\s+/g, ' ').trim().slice(0, 100) || (flow.rid ? `reproduce report ${flow.rid}` : `flow ${flow.name}`);
  return `issue #${iid}: ${note}`;
}

/**
 * @param {object} replay  replay.json (schema shakefix.replay/v1) or a *.flow.json
 * @param {{iid: string|number, baseUrlEnv?: string, defaultBaseUrl?: string}} opts
 * @returns {string} TypeScript source of a @playwright/test spec
 */
export function generateSpec(replay, { iid, baseUrlEnv = 'BASE_URL', defaultBaseUrl = 'http://localhost:8080' } = {}) {
  if (iid === undefined || iid === null || iid === '') throw new TypeError('generateSpec: iid is required');
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(baseUrlEnv)) throw new TypeError(`generateSpec: invalid env var name "${baseUrlEnv}"`);
  const flow = normalizeFlow(replay);
  const steps = planSteps(flow.actions);
  const exp = flow.expectation;
  const source = flow.rid ? `report ${flow.rid}` : `flow ${flow.name}`;

  const L = [];
  L.push(`// Generated by ShakeFix from ${source} — must FAIL before the fix and PASS after.`);
  const meta = [];
  if (replay.app && replay.app.name) meta.push(`App: ${replay.app.name}@${replay.app.version || '?'}`);
  if (replay.trigger) meta.push(`Trigger: ${replay.trigger}`);
  if (replay.device && Array.isArray(replay.device.viewport)) meta.push(`Device viewport: ${replay.device.viewport.join('x')}`);
  if (meta.length) L.push(`// ${comment(meta.join(' · '))}`);
  if (flow.note) L.push(`// Reporter note: ${comment(flow.note)}`);
  L.push(`// Regenerate: node packages/replay/bin/to-spec.js <replay.json> <out.spec.ts> --iid ${iid}`);
  L.push(`import { test, expect } from '@playwright/test';`);
  L.push('');
  L.push(`test.use({ baseURL: process.env.${baseUrlEnv} || ${q(defaultBaseUrl)} });`);
  L.push('');
  L.push(`test(${q(specTitle(flow, iid))}, async ({ page, request }) => {`);
  const body = [];
  if (!exp) {
    body.push('const errors: string[] = [];');
    body.push(`page.on('console', (msg) => { if (msg.type() === 'error' && !/favicon/i.test(msg.text())) errors.push(msg.text()); });`);
    body.push(`page.on('pageerror', (err) => errors.push(String(err)));`);
    body.push('');
  }
  body.push('// Reset seeded data (test hooks may be disabled — ignore failures).');
  body.push(`await request.post('/api/__test/reset').catch(() => undefined);`);
  body.push(`await page.goto(${q(flow.startRoute)});`);
  for (const s of steps) {
    body.push('');
    body.push(...stepCode(s));
  }
  body.push('');
  if (exp) {
    body.push(`// Expectation inferred by the SDK: ${exp.testid} ${exp.state}${exp.state === 'text' ? ` "${comment(exp.text ?? '')}"` : ''}`);
    body.push(...expectationCode(exp));
  } else {
    body.push('// No expectation recorded: the flow must finish without console errors or an error banner.');
    body.push(`await expect(page.getByTestId('error-banner')).toBeHidden();`);
    body.push('expect(errors).toEqual([]);');
  }
  for (const line of body) L.push(line ? `  ${line}` : '');
  L.push('});');
  L.push('');
  return L.join('\n');
}
