// Role prompts for the local agent runner, derived from the Duo flow YAML (the source of truth).
//
// .gitlab/duo/flows/shakefix.yml  --(scripts/sync-prompts.mjs)-->  .shakefix/prompts/<role>.md
//
// No YAML dependency: the flow file has a fixed, simple layout (components with a toolset list,
// prompts with `system: |` / `user: |` literal blocks), and this extractor reads exactly that.

import { readFile, readdir } from 'node:fs/promises';
import { join } from 'node:path';

export const FLOW_PATH = '.gitlab/duo/flows/shakefix.yml';
export const PROMPTS_DIR = '.shakefix/prompts';
export const ROLES = Object.freeze(['triage_nurse', 'surgeon', 'attending', 'discharge']);

const indentOf = (line) => line.length - line.trimStart().length;
const unquote = (s) => String(s).trim().replace(/^["']|["']$/g, '');

/** Read a YAML literal block (`key: |`) starting after line index `i`; returns [text, nextIndex]. */
function literalBlock(lines, i, keyIndent) {
  const body = [];
  let j = i + 1;
  for (; j < lines.length; j++) {
    const l = lines[j];
    if (l.trim() === '') { body.push(''); continue; }
    if (indentOf(l) <= keyIndent) break;
    body.push(l);
  }
  while (body.length && body[body.length - 1] === '') body.pop();
  const ind = Math.min(...body.filter((l) => l !== '').map(indentOf));
  const text = body.map((l) => (l === '' ? '' : l.slice(ind))).join('\n');
  return [text + '\n', j]; // "|" (clip) keeps exactly one trailing newline
}

/**
 * Parse the parts of the flow YAML the local runner needs.
 * Returns { components: {name: {promptId, toolset:[]}}, prompts: {promptId: {name, system, user}} }.
 */
export function parseFlow(yamlText) {
  const lines = String(yamlText).replace(/\r\n/g, '\n').split('\n');
  const components = {};
  const prompts = {};
  let section = null;
  let comp = null;
  let prompt = null;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (/^\S/.test(line) && !line.startsWith('#')) {
      section = line.replace(/:.*$/, '').trim();
      comp = null;
      prompt = null;
      continue;
    }
    const t = line.trim();
    if (section === 'components') {
      let m = /^- name:\s*(.+)$/.exec(t);
      if (m) { comp = { promptId: null, toolset: [] }; components[unquote(m[1])] = comp; continue; }
      if (!comp) continue;
      m = /^prompt_id:\s*(.+)$/.exec(t);
      if (m) { comp.promptId = unquote(m[1]); continue; }
      m = /^toolset:\s*(.*)$/.exec(t);
      if (m) {
        if (m[1].startsWith('[')) {
          comp.toolset = m[1].replace(/[[\]]/g, '').split(',').map(unquote).filter(Boolean);
        } else {
          const ind = indentOf(line);
          for (let j = i + 1; j < lines.length; j++) {
            const mm = /^- (.+)$/.exec(lines[j].trim());
            if (!mm || indentOf(lines[j]) < ind) break;
            comp.toolset.push(unquote(mm[1]));
            i = j;
          }
        }
      }
    } else if (section === 'prompts') {
      let m = /^- prompt_id:\s*(.+)$/.exec(t);
      if (m) { prompt = { name: null, system: '', user: '' }; prompts[unquote(m[1])] = prompt; continue; }
      if (!prompt) continue;
      m = /^name:\s*(.+)$/.exec(t);
      if (m && !prompt.name) { prompt.name = unquote(m[1]); continue; }
      m = /^(system|user):\s*\|\s*$/.exec(t);
      if (m) {
        const [text, next] = literalBlock(lines, i, indentOf(line));
        prompt[m[1]] = text;
        i = next - 1;
      }
    }
  }
  return { components, prompts };
}

/** Roles in flow order with their prompts and toolsets. */
export function rolesFromFlow(yamlText) {
  const { components, prompts } = parseFlow(yamlText);
  return ROLES.filter((r) => components[r]).map((role) => {
    const c = components[role];
    const p = prompts[c.promptId] || {};
    return { role, promptId: c.promptId, name: p.name || role, toolset: c.toolset, system: p.system || '', user: p.user || '' };
  });
}

const HEADER = (r) =>
  `<!-- GENERATED by scripts/sync-prompts.mjs from ${FLOW_PATH} (prompt_id: ${r.promptId}). ` +
  'Do not edit: change the YAML and run `node scripts/sync-prompts.mjs`. -->';

/** Render one .shakefix/prompts/<role>.md file. */
export function renderPromptFile(r) {
  return [
    HEADER(r),
    `<!-- name: ${r.name} -->`,
    `<!-- tools: ${r.toolset.join(',')} -->`,
    '<!-- system -->',
    r.system.replace(/\n$/, ''),
    '<!-- user -->',
    r.user.replace(/\n$/, ''),
    '',
  ].join('\n');
}

/** Parse a rendered prompt file back into {role, name, toolset, system, user}. */
export function parsePromptFile(text, role) {
  const s = String(text).replace(/\r\n/g, '\n');
  const name = /<!-- name: (.*?) -->/.exec(s)?.[1] ?? role;
  const tools = /<!-- tools: (.*?) -->/.exec(s)?.[1] ?? '';
  const sys = s.indexOf('<!-- system -->\n');
  const usr = s.indexOf('\n<!-- user -->\n');
  if (sys < 0 || usr < 0) throw new Error(`prompt file for ${role} is missing <!-- system --> / <!-- user --> markers`);
  return {
    role,
    name,
    toolset: tools.split(',').map((x) => x.trim()).filter(Boolean),
    system: s.slice(sys + '<!-- system -->\n'.length, usr) + '\n',
    user: s.slice(usr + '\n<!-- user -->\n'.length).replace(/\n$/, '') + '\n',
  };
}

/** Expected file map {relativePath: content} for a flow YAML text. */
export function expectedPromptFiles(yamlText) {
  const out = {};
  for (const r of rolesFromFlow(yamlText)) out[`${PROMPTS_DIR}/${r.role}.md`] = renderPromptFile(r);
  return out;
}

/** Load the role prompts the local runner uses (from .shakefix/prompts, in flow order). */
export async function loadRolePrompts(repoRoot) {
  const dir = join(repoRoot, PROMPTS_DIR);
  const files = new Set(await readdir(dir).catch(() => []));
  const out = [];
  for (const role of ROLES) {
    if (!files.has(`${role}.md`)) throw new Error(`missing ${PROMPTS_DIR}/${role}.md (run node scripts/sync-prompts.mjs)`);
    out.push(parsePromptFile(await readFile(join(dir, `${role}.md`), 'utf8'), role));
  }
  return out;
}

/** Fill {{placeholders}}; unknown ones become "(none)". */
export function fillTemplate(tpl, vars) {
  return String(tpl).replace(/\{\{\s*(\w+)\s*\}\}/g, (_m, k) => {
    const v = vars[k];
    if (v === undefined || v === null || v === '') return '(none)';
    return typeof v === 'string' ? v : JSON.stringify(v);
  });
}
