// Scoring for the graded eval ("graded, not vibes"). Pure: results in, numbers + markdown out.
// A metric with nothing measured is reported as "not run", never as 0 % or 100 %.

/** {n, of, pct} or {notRun: true} */
export function rate(n, of) {
  if (!of) return { n: 0, of: 0, pct: null, notRun: true };
  return { n, of, pct: Math.round((1000 * n) / of) / 10, notRun: false };
}

export function median(values) {
  const v = values.filter((x) => Number.isFinite(x)).sort((a, b) => a - b);
  if (!v.length) return null;
  const m = Math.floor(v.length / 2);
  return v.length % 2 ? v[m] : (v[m - 1] + v[m]) / 2;
}

/**
 * Per-scenario result shape (see run.mjs):
 * { id, kind: 'bug'|'trap', trap?, reproduction: {ran, failedOnBuggy, control?: {ran, passed}},
 *   fix: {graded, specPasses, unitGreen, source} | null,
 *   refusal: {evaluated, refused, basis} | null, shakeToMrS: number|null }
 */
export function scoreResults(results) {
  const bugs = results.filter((r) => r.kind === 'bug');
  const traps = results.filter((r) => r.kind === 'trap');

  const reproRan = bugs.filter((r) => r.reproduction?.ran);
  const reproduced = reproRan.filter((r) => r.reproduction.failedOnBuggy === true);
  const controls = bugs.filter((r) => r.reproduction?.control?.ran);
  const controlsPassed = controls.filter((r) => r.reproduction.control.passed === true);
  const sdkOnlyRan = reproRan.filter((r) => typeof r.reproduction.sdkOnlyFailedOnBuggy === 'boolean');
  const sdkOnly = sdkOnlyRan.filter((r) => r.reproduction.sdkOnlyFailedOnBuggy === true);

  const graded = bugs.filter((r) => r.fix?.graded);
  const fixed = graded.filter((r) => r.fix.specPasses === true && r.fix.unitGreen === true);
  // A false fix: a fix was delivered (commit / MR) but it does not pass its own regression spec or unit tests,
  // or a trap got a fix at all.
  const attempts = [...graded, ...traps.filter((r) => r.fix?.graded)];
  const falseFixes = attempts.filter((r) => r.kind === 'trap' || !(r.fix.specPasses === true && r.fix.unitGreen === true));

  const trapsEvaluated = traps.filter((r) => r.refusal?.evaluated);
  const refused = trapsEvaluated.filter((r) => r.refusal.refused === true);

  const mrTimes = results.map((r) => r.shakeToMrS).filter((x) => Number.isFinite(x));

  return {
    scenarios: results.length,
    bugs: bugs.length,
    traps: traps.length,
    reproduced: rate(reproduced.length, reproRan.length),
    reproducedSdkOnly: rate(sdkOnly.length, sdkOnlyRan.length),
    controlsPassed: rate(controlsPassed.length, controls.length),
    fixed: rate(fixed.length, graded.length),
    falseFix: rate(falseFixes.length, attempts.length),
    trapsRefused: rate(refused.length, trapsEvaluated.length),
    medianShakeToMrS: median(mrTimes),
    shakeToMrSamples: mrTimes.length,
  };
}

const pct = (r) => (r.notRun ? 'not run' : `${r.pct}% (${r.n}/${r.of})`);
const frac = (r) => (r.notRun ? 'not run' : `${r.n}/${r.of}`);

export function formatSeconds(s) {
  if (!Number.isFinite(s)) return 'not run';
  const t = Math.round(s);
  return t < 60 ? `${t}s` : `${Math.floor(t / 60)}m ${String(t % 60).padStart(2, '0')}s`;
}

const yesNo = (v) => (v === true ? '✅' : v === false ? '❌' : '—');

/** Markdown scorecard. Every number comes from `run`; nothing is filled in by hand. */
export function scorecardMarkdown(run) {
  const s = run.score;
  const L = [];
  L.push(`# ShakeFix graded eval — ${run.runAt.slice(0, 10)}`);
  L.push('');
  L.push(`Mode: \`${run.mode}\` · git \`${run.git?.head ?? '?'}\`${run.git?.dirty ? ' (uncommitted changes)' : ''} · ${s.scenarios} scenarios (${s.bugs} bugs, ${s.traps} traps) · generated by \`node evals/run.mjs\`.`);
  L.push('');
  L.push('| Metric | Result |');
  L.push('|---|---|');
  L.push(`| Reproduced (regression spec fails on the buggy build) | ${pct(s.reproduced)} |`);
  L.push(`| ↳ from the SDK replay alone (no expectation added from the note) | ${pct(s.reproducedSdkOnly)} |`);
  L.push(`| ↳ control: same spec passes on the clean build | ${pct(s.controlsPassed)} |`);
  L.push(`| Fixed (spec passes on the fix + unit tests green) | ${pct(s.fixed)} |`);
  L.push(`| False fixes (delivered fix that fails its own spec or unit tests, or any fix for a trap) | ${pct(s.falseFix)} |`);
  L.push(`| Traps refused | ${frac(s.trapsRefused)} |`);
  L.push(`| Median shake → MR | ${s.shakeToMrSamples ? `${formatSeconds(s.medianShakeToMrS)} (n=${s.shakeToMrSamples})` : 'not run'} |`);
  L.push('');
  L.push('| # | Scenario | Build | Reproduced | Control | Fixed | Refused | Shake → MR | Notes |');
  L.push('|---|---|---|---|---|---|---|---|---|');
  for (const r of run.scenarios) {
    const build = r.evalBug ? `EVAL_BUG=${r.evalBug}` : 'main';
    const repro = r.reproduction?.ran ? (r.kind === 'trap' ? (r.reproduction.failedOnBuggy ? 'yes (!)' : 'no') : yesNo(r.reproduction.failedOnBuggy)) : 'not run';
    const control = r.reproduction?.control?.ran ? yesNo(r.reproduction.control.passed) : '—';
    const fixed = r.fix?.graded ? `${yesNo(r.fix.specPasses && r.fix.unitGreen)} ${r.fix.source ?? ''}`.trim() : 'not run';
    const refused = r.kind === 'trap' ? (r.refusal?.evaluated ? `${yesNo(r.refusal.refused)} ${r.refusal.basis ?? ''}`.trim() : 'not run') : '—';
    const mr = Number.isFinite(r.shakeToMrS) ? formatSeconds(r.shakeToMrS) : '—';
    const notes = (r.notes ?? []).join('; ').replace(/\|/g, '\\|');
    L.push(`| ${r.id} | ${r.title.replace(/\|/g, '\\|')} | ${build} | ${repro} | ${control} | ${fixed} | ${refused} | ${mr} | ${notes} |`);
  }
  L.push('');
  L.push('**How to read this.** "Reproduced" runs the regression spec that ShakeFix generates from the replay the SDK recorded while the');
  L.push('scenario\'s steps were played on the buggy build. Where the SDK cannot infer what "working" means, the spec uses the');
  L.push('expectation stated in the scenario (what the Triage Nurse is asked to derive from the reporter\'s note); the SDK-only row');
  L.push('shows the rate without that help. "Control" proves the same spec passes once the bug is switched off (eval bugs only;');
  L.push('B1–B4 are live on main). "Fixed", "false fixes" and "shake → MR" need a fix to grade: a fix ref (`--fix-ref`), the local');
  L.push('agent runner (`MODEL_PROVIDER`) or GitLab mode. Anything not measured says "not run".');
  L.push('');
  return L.join('\n');
}
