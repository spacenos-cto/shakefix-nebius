#!/usr/bin/env node
// Wrap .gitlab/duo/flows/shakefix.yml in the envelope the AI Catalog CI/CD component expects
// (gitlab.com/components/ai-catalog: name, description, public, definition) and write it to
// ai-catalog/flows/shakefix.yml. Text-level indent, no YAML dependency, so the definition is
// byte-for-byte the flow we test in the UI.
// Usage: node scripts/ci/build-catalog-flow.mjs [src] [outDir]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';

const src = process.argv[2] ?? '.gitlab/duo/flows/shakefix.yml';
const outDir = process.argv[3] ?? 'ai-catalog/flows';
const out = join(outDir, 'shakefix.yml');

const lines = readFileSync(src, 'utf8').split(/\r?\n/);
const start = lines.findIndex((line) => line.trim() && !line.trim().startsWith('#'));
const body = lines
  .slice(Math.max(start, 0)) // drop the leading comment header only; block scalars stay intact
  .map((line) => (line.length ? `  ${line}` : ''))
  .join('\n')
  .replace(/\n{3,}/g, '\n\n');

const envelope = [
  '# GENERATED by scripts/ci/build-catalog-flow.mjs from .gitlab/duo/flows/shakefix.yml. Do not edit.',
  'name: "ShakeFix ER"',
  'description: "Shake report to failing spec to minimal fix to review to MR with a Patient Chart. Four ER agents: Triage Nurse, Surgeon, Attending, Discharge."',
  'public: true',
  'definition:',
  body.trimEnd(),
  '',
].join('\n');

if (Buffer.byteLength(envelope) > 40 * 1024) {
  console.error(`flow is ${Buffer.byteLength(envelope)} bytes; AI Catalog limit is 40 KiB`);
  process.exit(1);
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, envelope);
console.log(`wrote ${out} (${Buffer.byteLength(envelope)} bytes)`);
