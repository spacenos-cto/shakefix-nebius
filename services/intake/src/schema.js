// zod schemas. Shapes follow docs/CONTRACTS.md ("shakefix.replay/v1") exactly.
// Unknown keys are stripped (zod default), so nothing unexpected is ever committed
// to the repository or rendered into an issue.
import { z } from 'zod';
import { E164_RE, VOICE_MIME } from './voice.js';

/** Contract: "rid": "r_<yyyymmdd>_<6 hex>" */
export const RID_RE = /^r_\d{8}_[0-9a-f]{6}$/;

export const ridSchema = z.string().regex(RID_RE, 'rid must match r_<yyyymmdd>_<6 hex>');

const s = (max) => z.string().max(max);

export const actionSchema = z.object({
  t: z.number().finite().nonnegative(),
  type: z.enum(['click', 'input', 'change', 'navigate', 'submit']),
  testid: s(200).optional(),
  selector: s(1000),
  value: s(2000).optional(),
  route: s(2000),
});

export const expectationSchema = z.object({
  testid: s(200),
  state: z.enum(['visible', 'hidden', 'text']),
  text: s(2000).optional(),
});

export const consoleEntrySchema = z.object({
  level: z.enum(['error', 'warn']),
  msg: s(4000),
  stack: s(16000).optional(),
});

export const networkEntrySchema = z.object({
  method: s(16),
  path: s(2000),
  status: z.number().int(),
  ms: z.number().finite().nonnegative(),
});

export const replaySchema = z.object({
  schema: z.literal('shakefix.replay/v1'),
  rid: ridSchema,
  app: z.object({ name: s(100).min(1), version: s(100), baseUrl: s(2000) }),
  device: z.object({
    ua: s(1000),
    viewport: z.tuple([z.number().int().nonnegative(), z.number().int().nonnegative()]),
    touch: z.boolean(),
  }),
  trigger: z.enum(['shake', 'bubble', 'hotkey', 'auto-error', 'rage-click']),
  note: s(2000),
  startRoute: s(2000),
  actions: z.array(actionSchema).max(200),
  // Contract says `expectation: {...} | null`; a missing key is normalised to null.
  expectation: expectationSchema.nullable().optional().transform((v) => v ?? null),
  console: z.array(consoleEntrySchema).max(100),
  network: z.array(networkEntrySchema).max(200),
});

export const pushSubscriptionSchema = z.object({
  endpoint: z.string().url().max(2000).startsWith('https://'),
  expirationTime: z.number().nullable().optional(),
  keys: z.object({ p256dh: s(200).min(1), auth: s(200).min(1) }),
});

/** Opaque per-device id generated by the SDK (localStorage). Used only to dedupe verdicts. */
export const deviceIdSchema = z.string().min(8).max(128).regex(/^[A-Za-z0-9_:-]+$/, 'deviceId must be [A-Za-z0-9_:-]');

/** The reporter's spoken description (SDK mic button). ~30 s of opus is well under the limit. */
export const voiceNoteSchema = z.object({
  audio: z.string().min(1).max(1_200_000), // base64
  mime: z.enum(VOICE_MIME),
});

/** "Call me to check it's fixed": the reporter's own number and explicit consent. */
export const callbackSchema = z.object({
  phone: z.string().trim().regex(E164_RE, 'phone must be E.164, e.g. +14155550100'),
  consent: z.literal(true),
});

export const reportBodySchema = z.object({
  replay: replaySchema,
  // base64 PNG, optionally as a data: URL. Optional (auto-error reports may lack one).
  screenshotPng: z.string().nullish(), // the SDK sends null when html2canvas fails
  pushSubscription: pushSubscriptionSchema.nullable().optional(),
  deviceId: deviceIdSchema.optional(),
  voiceNote: voiceNoteSchema.nullish(),
  callback: callbackSchema.nullish(),
});

/** Body of POST /v1/oncall/call (sent by CI rollback.sh). */
export const oncallBodySchema = z.object({
  issues: z.array(z.number().int().positive()).max(20).default([]),
  version: s(64).optional(),
  prevRevision: s(200).optional(),
  reason: s(500).optional(),
});

export const VERDICTS = ['confirmed', 'rejected'];

/**
 * Body of POST /v1/reports/:rid/verdict (public, from the SDK or the service worker).
 * `rejected` must carry the fresh replay recorded when the reporter re-reported.
 */
export const verdictBodySchema = z
  .object({
    verdict: z.enum(VERDICTS),
    deviceId: deviceIdSchema.optional(),
    replay: replaySchema.optional(),
    pushSubscription: pushSubscriptionSchema.nullable().optional(),
  })
  .superRefine((b, ctx) => {
    if (b.verdict === 'rejected' && !b.replay) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, path: ['replay'], message: 'replay is required when verdict is rejected' });
    }
  });

const proofSchema = z.object({
  intended: z.number().int().nonnegative(),
  unintended: z.number().int().nonnegative(),
});

/** Body of POST /v1/reports/:rid/fixed (sent by CI notify.sh). All fields optional. */
export const fixedBodySchema = z
  .object({
    url: s(2000).optional(),
    mrIid: z.number().int().positive().optional(),
    proof: proofSchema.optional(),
    // Optional run cost for the stopwatch line (e.g. model + CI spend). Only shown when sent.
    cost: z.object({ usd: z.number().nonnegative().max(10_000), source: s(200).optional() }).optional(),
  })
  .default({});

/** Body of POST /v1/reports/:rid/reoperate (sent by CI proof-gate.sh as {"mrIid":N}; `mr` also accepted). */
export const reoperateBodySchema = z.preprocess(
  (b) => (b && typeof b === 'object' && b.mr == null && b.mrIid != null ? { ...b, mr: b.mrIid } : b),
  z.object({
    mr: z.number().int().positive(),
    issueIid: z.number().int().positive().optional(),
    proof: proofSchema.optional(),
  }),
);

const hex64 = z.string().trim().toLowerCase().regex(/^[0-9a-f]{64}$/, 'must be 64 hex chars');

/** Query of GET /v1/certificates/verify (public). */
export const certVerifyQuerySchema = z.object({
  rid: ridSchema,
  digest: hex64,
  signature: hex64,
});

/** Format zod errors without echoing submitted values. */
export function zodIssues(error) {
  return error.issues.slice(0, 20).map((i) => ({ path: i.path.join('.'), message: i.message }));
}
